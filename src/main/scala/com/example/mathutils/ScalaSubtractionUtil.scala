package com.example.mathutils

import com.example.mathutils.SubtractionUtil

/**
 * A Scala utility for performing subtractions.
 */
object ScalaSubtractionUtil:

  /**
   * Performs the subtraction between the provided numbers.
   *
   * @param a the first number
   * @param b the second number
   * @return the result of the subtraction between the two numbers.
   */
  def subtract(a: Int, b: Int): Int = SubtractionUtil.subtract(a, b)